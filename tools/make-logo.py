#!/usr/bin/env python3
"""Build-time logo converter: assets/logo-1000.jpg -> src/logo-art.js
Half-block (upper/lower) rendering: each terminal cell shows 2 vertical pixels.
Needs Pillow. Runtime has zero dependencies (the output is pre-generated).
Usage: python3 tools/make-logo.py [width_in_cells]   (default 40)
"""
import json, os, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "logo-1000.jpg")
OUT = os.path.join(ROOT, "src", "logo-art.js")
W = int(sys.argv[1]) if len(sys.argv) > 1 else 40
DARK = 45  # luminance below this counts as background

im = Image.open(SRC).convert("RGB")
# crop to the gold artwork (ignore black margins)
mask = im.point(lambda v: 255 if v > 90 else 0).convert("L")
bbox = mask.getbbox()
pad = 6
l, t, r, b = bbox
im = im.crop((max(l - pad, 0), max(t - pad, 0), min(r + pad, im.width), min(b + pad, im.height)))
H = round(W * im.height / im.width)
H += H % 2  # even number of pixel rows
im = im.resize((W, H), Image.LANCZOS)
px = im.load()


def lum(c):
    return 0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2]


def to256(c):
    def q(v):
        return 0 if v < 48 else 1 if v < 115 else (v - 35) // 40
    return 16 + 36 * q(c[0]) + 6 * q(c[1]) + q(c[2])


def render(mode):
    rows = []
    for y in range(0, H, 2):
        line, last = "", None
        for x in range(W):
            top, bot = px[x, y], px[x, y + 1]
            td, bd = lum(top) < DARK, lum(bot) < DARK
            if td and bd:
                ch, style = " ", ("0",)
            elif bd:
                ch, style = "▀", ("fg", top)
            elif td:
                ch, style = "▄", ("fg", bot)
            else:
                ch, style = "▀", ("fgbg", top, bot)
            if mode == "plain":
                if td and bd: seg = " "
                elif bd: seg = "▀"
                elif td: seg = "▄"
                else: seg = "█"
                line += seg
                continue
            if style[0] == "0":
                code = "\x1b[0m"
            elif mode == "truecolor":
                if style[0] == "fg":
                    c = style[1]; code = f"\x1b[0;38;2;{c[0]};{c[1]};{c[2]}m"
                else:
                    c, d = style[1], style[2]; code = f"\x1b[38;2;{c[0]};{c[1]};{c[2]};48;2;{d[0]};{d[1]};{d[2]}m"
            else:
                if style[0] == "fg":
                    code = f"\x1b[0;38;5;{to256(style[1])}m"
                else:
                    code = f"\x1b[38;5;{to256(style[1])};48;5;{to256(style[2])}m"
            if code != last:
                line += code; last = code
            line += ch
        if mode != "plain":
            line += "\x1b[0m"
        rows.append(line.rstrip() if mode == "plain" else line)
    return "\n".join(rows)


art = {"width": W, "height": H // 2,
       "truecolor": render("truecolor"), "ansi256": render("ansi256"), "plain": render("plain")}
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("// GENERATED by tools/make-logo.py from assets/logo-1000.jpg. Do not edit by hand.\n")
    f.write("export default " + json.dumps(art, ensure_ascii=True, indent=2) + ";\n")
print(f"wrote {OUT}: {W} cols x {H // 2} rows")
